"""Phase 3: paper vs. ours for the BiasMedQA protocol -> results/reproduction/comparison.{md,json}.

Paper numbers: results/reproduction/schmidgall2024_supp_tables.csv (transcribed from Supplementary Tables 1-4; row averages
verified). Ours: results/reproduction/<run>/summary.json (paper convention: non-responses excluded).
Also re-derives the paper's headline per-bias drops from its own Table 1 in both possible units.
Usage: python scripts/compare_reproduction.py [--runs gpt41mini_n600_s0 ...]
"""
from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src.data.bias import BIASMEDQA  # noqa: E402
from src.utils.provenance import provenance  # noqa: E402

PAPER_HEADLINE = {"false_consensus": 24.9, "frequency": 18.2, "recency": 12.9, "confirmation": 8.1}  # paper text
STRATS = ["none", "edu", "oneshot", "fewshot"]


def paper_table() -> dict:
    t: dict = {}
    for r in csv.DictReader(open(ROOT / "results/reproduction/schmidgall2024_supp_tables.csv")):
        t.setdefault(r["strategy"], {})[r["model"]] = {k: 100 * float(v) for k, v in r.items()
                                                      if k not in ("strategy", "model")}
    return t


def spearman(a: list[float], b: list[float]) -> float:
    from scipy.stats import spearmanr
    return float(spearmanr(a, b).statistic)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", nargs="*", default=None, help="result dirs under results/reproduction (default: all non-pilot)")
    args = ap.parse_args()
    P = paper_table()
    res: dict = {"paper": {}, "ours": {}}

    # 1) units of the paper's headline per-bias drops, from its own Table 1 (no mitigation)
    none = P["none"]
    units = {}
    for b, claimed in PAPER_HEADLINE.items():
        pp = float(np.mean([m["nobias"] - m[b] for m in none.values()]))
        rel = float(np.mean([100 * (m["nobias"] - m[b]) / m["nobias"] for m in none.values()]))
        units[b] = {"claimed": claimed, "mean_pp_drop_6_models": round(pp, 1), "mean_relative_drop_pct": round(rel, 1)}
    res["paper"]["headline_units_check"] = units
    res["paper"]["avg_drop_pp_per_model"] = {k: round(m["nobias"] - m["avg"], 1) for k, m in none.items()}
    res["paper"]["mitigation_gain_pp_per_model"] = {
        s: {k: round(P[s][k]["avg"] - none[k]["avg"], 1) for k in P[s]} for s in STRATS[1:]}
    paper_sev = [float(np.mean([m["nobias"] - m[b] for m in none.values()])) for b in BIASMEDQA]

    # 2) ours
    rdir = ROOT / "results/reproduction"
    runs = args.runs or sorted(p.name for p in rdir.iterdir() if (p / "summary.json").exists() and "pilot" not in p.name)
    for run in runs:
        s = json.loads((rdir / run / "summary.json").read_text())
        tab = s["paper_style_table_excl_nonresponse"]
        if "none" not in tab:
            res["ours"][run] = {"note": "incomplete or invalid scoring", "meta": s.get("meta")}
            continue
        sev = [tab["none"]["nobias"] - tab["none"][b] for b in BIASMEDQA]
        res["ours"][run] = {
            "n": s["n"], "table": tab, "avg_drop_pp": round(tab["none"]["nobias"] - tab["none"]["avg"], 1),
            "mitigation_gain_pp": {k: round(v, 1) for k, v in s.get("mitigation_gain_pp_excl", {}).items()},
            "max_nonresponse_pct": max(s["nonresponse_rate"].values()),
            "drops_ci_strict": {b: [round(x, 1) for x in s["drops_vs_nobias_strict"][b]["ci95_pp"]] for b in BIASMEDQA},
            "bias_severity_spearman_vs_paper": round(spearman(sev, paper_sev), 2),
            "meta": s.get("meta")}
    res["provenance"] = provenance(vars(args), __file__)
    (rdir / "comparison.json").write_text(json.dumps(res, indent=1))

    # 3) markdown
    L = ["# BiasMedQA reproduction: paper vs ours", "",
         "Generated by `scripts/compare_reproduction.py`. Accuracy in %, non-responses excluded (paper convention).",
         "Paper: 5-option MedQA **test** (1,273). Ours: 5-option MedQA **dev**, fixed random subset (D017).", "",
         "## No mitigation: accuracy by bias", "",
         "| model | source | no bias | " + " | ".join(BIASMEDQA) + " | avg | avg drop |",
         "|---|---|---|" + "---|" * len(BIASMEDQA) + "---|---|"]
    for k, m in none.items():
        L.append(f"| {k} | paper | {m['nobias']:.1f} | " + " | ".join(f"{m[b]:.1f}" for b in BIASMEDQA)
                 + f" | {m['avg']:.1f} | {m['nobias'] - m['avg']:.1f} |")
    for run, o in res["ours"].items():
        if "table" not in o:
            L.append(f"| {run} | ours | {o['note']} |"); continue
        t = o["table"]["none"]
        L.append(f"| {run} | ours (n={o['n']}) | {t['nobias']:.1f} | " + " | ".join(f"{t[b]:.1f}" for b in BIASMEDQA)
                 + f" | {t['avg']:.1f} | {o['avg_drop_pp']:.1f} |")
    L += ["", "## Mitigation gain over no mitigation (avg over 7 biases, pp)", "",
          "| model | source | education | one-shot | few-shot |", "|---|---|---|---|---|"]
    for k in none:
        g = res["paper"]["mitigation_gain_pp_per_model"]
        L.append(f"| {k} | paper | " + " | ".join(str(g[s].get(k, "n/a")) for s in STRATS[1:]) + " |")
    for run, o in res["ours"].items():
        if "table" in o:
            L.append(f"| {run} | ours | " + " | ".join(str(o["mitigation_gain_pp"].get(s, "not run"))
                                                       for s in STRATS[1:]) + " |")
    L += ["", "## Do the same biases hurt most? (Spearman of per-bias drops, ours vs paper 6-model mean)", ""]
    L += [f"- {run}: {o['bias_severity_spearman_vs_paper']}" for run, o in res["ours"].items() if "table" in o]
    L += ["", "## The paper's headline per-bias drops, recomputed from its own Supplementary Table 1", "",
          "| bias | claimed in text | mean pp drop (6 models) | mean relative drop % |", "|---|---|---|---|"]
    L += [f"| {b} | {u['claimed']} | {u['mean_pp_drop_6_models']} | {u['mean_relative_drop_pct']} |" for b, u in units.items()]
    L += ["", "## Protocol differences (why numbers are not directly comparable)", "",
          "- Models differ: none of the paper's six models is run here (GPT-4-0613, Mixtral-8x7B, GPT-3.5, PaLM-2,",
          "  Llama-2-70B and PMC-LLaMA are retired or do not fit a T4). gpt-4.1-mini is the nearest API relative of GPT-4.",
          "- Split: dev, a fixed 600-question subset (seed 0), vs the paper's full test split (1,273). Test is reserved (D017).",
          "- Answer extraction: open models by next-token letter probability (never a non-response); gpt-4.1-mini by",
          "  parsing free text at temperature 0. The paper parsed free text (GPT-3.5 used as a judge for 2 models).",
          "- One-shot was run only for gpt-4.1-mini; few-shot not for Med42 (GPU quota, D017).",
          "- Demonstrations: one fixed TRAIN pair per bias (seed 0); the paper's exact demonstration items are unknown.",
          "- Batch-composition noise on GPU (4-bit, fp16): repeated runs of the same condition differ by <= 1.0 pp (D019).",
          "", "Interpretation: see the reproduction section of the paper."]
    (rdir / "comparison.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
